def normalize_criterion(text: str, fallback: str) -> str:
    """Модель иногда пишет в criterion пункт чеклиста или служебный текст промпта.
    Приводим к названию свойства ISO 29148 или прохода; если не узнали — fallback."""
    t = (text or "").strip().strip("[]«»\"' ").strip()
    low = t.lower()
    for name in list(LENSES) + list(SINGLE) + list(SET):
        if name.lower() in low:
            return name
    for name, items in LENSES.items():
        for c in items:
            head = c.lower()[:40]
            if low and (low[:40] in c.lower() or head in low):
                return name
    if t and len(t.split()) <= 3 and not t.split()[0].isupper():
        return t[0].upper() + t[1:]
    return fallback
